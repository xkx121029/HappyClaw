-- Schema v30: cron run history and explicit scheduling semantics.

CREATE TABLE IF NOT EXISTS cron_runs (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id          TEXT NOT NULL UNIQUE,
  cron_id         TEXT NOT NULL REFERENCES cron_jobs(cron_id) ON DELETE CASCADE,
  trigger_kind    TEXT NOT NULL DEFAULT 'schedule',
  scheduled_for   BIGINT,
  status          TEXT NOT NULL DEFAULT 'running',
  attempt         INTEGER NOT NULL DEFAULT 1,
  started_at      BIGINT NOT NULL,
  finished_at     BIGINT,
  duration_ms     BIGINT,
  error           TEXT,
  created_at      BIGINT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_cron_runs_job_started
  ON cron_runs (cron_id, started_at DESC);

CREATE UNIQUE INDEX IF NOT EXISTS idx_cron_runs_slot
  ON cron_runs (cron_id, scheduled_for)
  WHERE scheduled_for IS NOT NULL;

ALTER TABLE cron_jobs ADD COLUMN IF NOT EXISTS timezone TEXT NOT NULL DEFAULT '';
ALTER TABLE cron_jobs ADD COLUMN IF NOT EXISTS next_run_at BIGINT;
ALTER TABLE cron_jobs ADD COLUMN IF NOT EXISTS max_retries INTEGER NOT NULL DEFAULT 0;
ALTER TABLE cron_jobs ADD COLUMN IF NOT EXISTS retry_backoff_seconds INTEGER NOT NULL DEFAULT 60;
ALTER TABLE cron_jobs ADD COLUMN IF NOT EXISTS catch_up_misses INTEGER NOT NULL DEFAULT 0;
ALTER TABLE cron_jobs ADD COLUMN IF NOT EXISTS consecutive_failures INTEGER NOT NULL DEFAULT 0;

UPDATE _schema_version SET version = 30;
