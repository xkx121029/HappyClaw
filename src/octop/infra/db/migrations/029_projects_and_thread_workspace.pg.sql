-- Schema v29: projects own workspaces; threads remember their project or session directory.

CREATE TABLE IF NOT EXISTS projects (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id  TEXT NOT NULL UNIQUE,
  user_id     INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name        TEXT NOT NULL,
  root_dir    TEXT,
  is_default  INTEGER NOT NULL DEFAULT 0,
  origin      TEXT NOT NULL DEFAULT 'manual',
  created_at  INTEGER NOT NULL,
  updated_at  INTEGER NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_projects_default_per_user
  ON projects (user_id) WHERE is_default = 1;

CREATE INDEX IF NOT EXISTS idx_projects_user_updated
  ON projects (user_id, updated_at DESC);

ALTER TABLE threads ADD COLUMN IF NOT EXISTS project_id TEXT;
ALTER TABLE threads ADD COLUMN IF NOT EXISTS workspace_kind TEXT;
ALTER TABLE threads ADD COLUMN IF NOT EXISTS workspace_dir TEXT;

CREATE INDEX IF NOT EXISTS idx_threads_project
  ON threads (project_id, last_active DESC);

UPDATE _schema_version SET version = 29;
