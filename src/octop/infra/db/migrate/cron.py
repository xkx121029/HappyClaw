"""Cron job and cron run history schema repairs."""

from __future__ import annotations

from octop.infra.db.migrate.introspect import (
    _drop_column,
    _ensure_column,
    _table_columns,
    _table_exists,
)
from octop.infra.db.pool import DatabasePool

_CRON_SCHEDULE_COLUMNS = (
    ("timezone", "TEXT NOT NULL DEFAULT ''"),
    ("next_run_at", "INTEGER"),
    ("max_retries", "INTEGER NOT NULL DEFAULT 0"),
    ("retry_backoff_seconds", "INTEGER NOT NULL DEFAULT 60"),
    ("catch_up_misses", "INTEGER NOT NULL DEFAULT 0"),
    ("consecutive_failures", "INTEGER NOT NULL DEFAULT 0"),
)


def _rename_legacy_cron_schedule_column(db: DatabasePool) -> None:
    """Rename pre-squash ``cron_jobs.trigger`` to ``schedule_spec``.

    Current inserts and reads use ``schedule_spec``. Databases created before
    that rename kept the old column, so cron creation failed with
    "no column named schedule_spec" even after later columns were added.
    """
    cols = _table_columns(db, "cron_jobs")
    if "trigger" not in cols:
        return
    if "schedule_spec" not in cols:
        with db.connect() as conn:
            conn.execute('ALTER TABLE cron_jobs RENAME COLUMN "trigger" TO schedule_spec')
        return
    with db.connect() as conn:
        conn.execute(
            'UPDATE cron_jobs SET schedule_spec = "trigger" '
            "WHERE schedule_spec IS NULL OR schedule_spec = ''"
        )
    _drop_column(db, "cron_jobs", "trigger")


def _ensure_cron_jobs_schema(db: DatabasePool) -> None:
    if not _table_exists(db, "cron_jobs"):
        return
    _rename_legacy_cron_schedule_column(db)
    _ensure_column(db, "cron_jobs", "name", "TEXT NOT NULL DEFAULT ''")
    _ensure_column(
        db,
        "cron_jobs",
        "task_type",
        "TEXT NOT NULL DEFAULT 'agent' CHECK (task_type IN ('text', 'agent'))",
    )
    _ensure_column(
        db,
        "cron_jobs",
        "mcp_servers",
        "TEXT NOT NULL DEFAULT '[]'",
    )


def _ensure_cron_run_schema(db: DatabasePool) -> None:
    """v30: per-run ledger plus explicit scheduling semantics on cron_jobs.

    Idempotent so restores from older physical schemas (or a version watermark
    that ran ahead) still end up with the columns and the table.
    """
    bigint = "BIGINT" if db.dialect == "postgresql" else "INTEGER"
    identity = (
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        if db.dialect == "postgresql"
        else "INTEGER PRIMARY KEY AUTOINCREMENT"
    )
    if _table_exists(db, "cron_jobs"):
        for column, definition in _CRON_SCHEDULE_COLUMNS:
            if column in {"next_run_at"}:
                definition = bigint
            _ensure_column(db, "cron_jobs", column, definition)
    if not _table_exists(db, "cron_jobs"):
        return
    with db.connect() as conn:
        conn.execute(
            "CREATE TABLE IF NOT EXISTS cron_runs ("
            f"id {identity}, "
            "run_id TEXT NOT NULL UNIQUE, "
            "cron_id TEXT NOT NULL REFERENCES cron_jobs(cron_id) ON DELETE CASCADE, "
            "trigger_kind TEXT NOT NULL DEFAULT 'schedule', "
            f"scheduled_for {bigint}, "
            "status TEXT NOT NULL DEFAULT 'running', "
            "attempt INTEGER NOT NULL DEFAULT 1, "
            f"started_at {bigint} NOT NULL, "
            f"finished_at {bigint}, "
            f"duration_ms {bigint}, "
            "error TEXT, "
            f"created_at {bigint} NOT NULL)"
        )
        conn.execute(
            "CREATE INDEX IF NOT EXISTS idx_cron_runs_job_started "
            "ON cron_runs (cron_id, started_at DESC)"
        )
        conn.execute(
            "CREATE UNIQUE INDEX IF NOT EXISTS idx_cron_runs_slot "
            "ON cron_runs (cron_id, scheduled_for) WHERE scheduled_for IS NOT NULL"
        )
    # v31 note column; kept here too so restores from a watermark ahead of v31
    # still end up with a complete ledger table.
    _ensure_column(db, "cron_runs", "note", "TEXT")
