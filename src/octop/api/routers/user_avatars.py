"""Read-only user avatar endpoint that survives single-user mode.

Multi-account management (``/api/users`` CRUD, ``/api/user-groups``) is fully
retired, but shared conversations still render each sender's portrait, so the
``GET /api/users/{user_id}/avatar`` URLs generated by chat history and
websocket payloads must keep answering. Upload and delete go through
``/api/auth/me/avatar`` for the local owner.
"""

from __future__ import annotations

from typing import Any

from fastapi import APIRouter, Depends

from octop.api.deps import current_user, get_server
from octop.infra.errors import ErrorCode, OctopError

router = APIRouter()


@router.get("/{user_id}/avatar")
async def get_user_avatar(
    user_id: int,
    _: Any = Depends(current_user),
    server: Any = Depends(get_server),
) -> Any:
    """Portrait for any signed-in user. Shared conversations show each sender."""
    from octop.infra.users.profile_avatar import avatar_response  # noqa: PLC0415

    if server.user_manager.get_row(user_id) is None:
        raise OctopError(ErrorCode.NOT_FOUND, "user not found")
    return avatar_response(server.services.avatars("user"), str(user_id))
