#!/usr/bin/env node
/**
 * Render `src/styles/tokens.generated.css` from `src/styles/tokens/tables.ts`…
 * except the table is TypeScript, so this script parses it with the same tiny
 * reader the design tokens used to need.
 *
 *   node scripts/gen-tokens.mjs           # write
 *   node scripts/gen-tokens.mjs --check   # verify, exit 1 on drift
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const tableFile = resolve(root, "src/styles/tokens/tables.ts");
const outFile = resolve(root, "src/styles/tokens.generated.css");

const HEADER = `/* AUTO-GENERATED by scripts/gen-tokens.mjs — do not edit by hand.
   Source: src/styles/tokens/tables.ts */`;

function readBlocks() {
  const source = readFileSync(tableFile, "utf8");
  const blocks = [];
  const blockRe = /selector:\s*("(?:[^"\\]|\\.)*"),\s*vars:\s*\[([\s\S]*?)\n    \],/g;
  for (const match of source.matchAll(blockRe)) {
    const selector = JSON.parse(match[1]);
    const vars = [];
    for (const pair of match[2].matchAll(/\[("(?:[^"\\]|\\.)*"),\s*("(?:[^"\\]|\\.)*")\]/g)) {
      vars.push([JSON.parse(pair[1]), JSON.parse(pair[2])]);
    }
    blocks.push({ selector, vars });
  }
  if (blocks.length === 0) throw new Error("no token blocks parsed from tables.ts");
  return blocks;
}

function build() {
  const lines = [HEADER, ""];
  for (const block of readBlocks()) {
    lines.push(`${block.selector} {`);
    for (const [name, value] of block.vars) lines.push(`  ${name}: ${value};`);
    lines.push("}", "");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

const next = build();

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outFile, "utf8");
  } catch {
    console.error("[gen-tokens] tokens.generated.css is missing; run without --check");
    process.exit(1);
  }
  if (current !== next) {
    console.error("[gen-tokens] tokens.generated.css is out of date; run `node scripts/gen-tokens.mjs`");
    process.exit(1);
  }
  console.log("[gen-tokens] OK");
} else {
  writeFileSync(outFile, next);
  console.log(`[gen-tokens] wrote ${outFile}`);
}
