#!/usr/bin/env node
/**
 * Generate `src/styles/tokens.generated.css` from the TypeScript token tables.
 *
 * The TS files under `src/styles/tokens/` are the single source of truth; this
 * script is the only writer of the CSS custom properties. Run with `--check` in
 * CI to fail when the committed CSS no longer matches the source.
 *
 *   node scripts/gen-tokens.mjs           # write
 *   node scripts/gen-tokens.mjs --check   # verify, exit 1 on drift
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const outFile = resolve(root, "src/styles/tokens.generated.css");

const HEADER = `/* AUTO-GENERATED by scripts/gen-tokens.mjs — do not edit by hand.
   Source: src/styles/tokens/{scales,colors}.ts */`;

/** Minimal TS literal reader: the token files are plain `as const` objects. */
function readConst(file, name) {
  const source = readFileSync(resolve(root, "src/styles/tokens", file), "utf8");
  // Allow an optional type annotation: `export const X: Record<…> = {`.
  const decl = new RegExp(`export const ${name}\\s*(?::[^=]+)?=\\s*\\{`);
  const match = decl.exec(source);
  if (!match) throw new Error(`${name} not found in ${file}`);
  const open = source.indexOf("{", match.index);
  let depth = 0;
  let end = -1;
  for (let i = open; i < source.length; i += 1) {
    if (source[i] === "{") depth += 1;
    else if (source[i] === "}") {
      depth -= 1;
      if (depth === 0) {
        end = i;
        break;
      }
    }
  }
  const body = source.slice(open + 1, end);
  const out = {};
  for (const line of body.split("\n")) {
    // Strip trailing `//` comments before matching so annotated entries parse.
    const withoutComment = line.replace(/\/\/.*$/, "");
    const match = withoutComment.match(/^\s*["']?([\w-]+)["']?\s*:\s*(.+?),?\s*$/);
    if (!match) continue;
    const [, key, rawValue] = match;
    // Strip a trailing comment and comma from the value itself. Doing it on the
    // captured value (not only on the line) keeps CRLF files and inline notes
    // out of the generated CSS — a value like `16, // section titles` is not a
    // valid CSS length and made `var(--fn-text-lg)` fall back at runtime.
    const value = rawValue
      .replace(/\/\/.*$/, "")
      .replace(/,\s*$/, "")
      .trim();
    if (value.startsWith("{")) continue;
    out[key] = value.replace(/^["']|["']$/g, "");
  }
  return out;
}

/** Read a nested `Record<Mode, {...}>` block such as SEMANTIC_COLORS. */
function readModeRecord(file, name) {
  const source = readFileSync(resolve(root, "src/styles/tokens", file), "utf8");
  const result = {};
  for (const mode of ["light", "dark"]) {
    const marker = `${mode}: {`;
    const start = source.indexOf(marker);
    if (start === -1) throw new Error(`${name}.${mode} not found`);
    const open = source.indexOf("{", start);
    let depth = 0;
    let end = -1;
    for (let i = open; i < source.length; i += 1) {
      if (source[i] === "{") depth += 1;
      else if (source[i] === "}") {
        depth -= 1;
        if (depth === 0) {
          end = i;
          break;
        }
      }
    }
    const body = source.slice(open + 1, end);
    const entries = {};
    for (const line of body.split("\n")) {
      const withoutComment = line.replace(/\/\/.*$/, "");
      const match = withoutComment.match(/^\s*(\w+)\s*:\s*(.+?),\s*$/);
      if (match) entries[match[1]] = match[2].replace(/^["']|["']$/g, "");
    }
    result[mode] = entries;
  }
  return result;
}

function px(value, unit = "px") {
  return /^-?[\d.]+$/.test(value) ? `${value}${unit}` : value;
}

function kebab(key) {
  return key.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}

function build() {
  const fontSize = readConst("scales.ts", "FONT_SIZE");
  const lineHeight = readConst("scales.ts", "LINE_HEIGHT");
  const fontWeight = readConst("scales.ts", "FONT_WEIGHT");
  const space = readConst("scales.ts", "SPACE");
  const radius = readConst("scales.ts", "RADIUS");
  const control = readConst("scales.ts", "CONTROL_HEIGHT");
  const layout = readConst("scales.ts", "LAYOUT");
  const cssVars = readConst("colors.ts", "SEMANTIC_CSS_VARS");
  const colors = readModeRecord("colors.ts", "SEMANTIC_COLORS");

  const lines = [HEADER, "", "/* ---------- SCALES (mode-independent) ---------- */", ":root {"];

  for (const [key, value] of Object.entries(fontSize)) {
    lines.push(`  --fn-text-${key}: ${px(value)};`);
  }
  for (const [key, value] of Object.entries(lineHeight)) {
    lines.push(`  --fn-leading-${key}: ${value};`);
  }
  for (const [key, value] of Object.entries(fontWeight)) {
    lines.push(`  --fn-weight-${key}: ${value};`);
  }
  for (const [key, value] of Object.entries(space)) {
    lines.push(`  --fn-space-${key}: ${px(value)};`);
  }
  for (const [key, value] of Object.entries(radius)) {
    lines.push(`  --fn-radius-${key}: ${px(value)};`);
  }
  for (const [key, value] of Object.entries(control)) {
    lines.push(`  --fn-control-height-${key}: ${px(value)};`);
  }
  for (const [key, value] of Object.entries(layout)) {
    lines.push(`  --fn-${kebab(key)}: ${px(value)};`);
  }
  lines.push("}", "");

  for (const mode of ["light", "dark"]) {
    const selector = mode === "light" ? ':root,\nhtml[data-theme="light"]' : 'html[data-theme="dark"]';
    lines.push(`/* ---------- ${mode.toUpperCase()} ---------- */`, `${selector} {`);
    for (const [role, varName] of Object.entries(cssVars)) {
      const value = colors[mode]?.[role];
      if (value === undefined) continue;
      lines.push(`  ${varName}: ${value};`);
    }
    lines.push("}", "");
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

const next = build();

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outFile, "utf8");
  } catch {
    console.error("[gen-tokens] tokens.generated.css is missing; run without --check");
    process.exit(1);
  }
  if (current !== next) {
    console.error("[gen-tokens] tokens.generated.css is out of date; run `node scripts/gen-tokens.mjs`");
    process.exit(1);
  }
  console.log("[gen-tokens] OK");
} else {
  writeFileSync(outFile, next);
  console.log(`[gen-tokens] wrote ${outFile}`);
}
